#  Function to get the cell block from an ASE atoms object, values in bohr -> this might produce some spikes in the 
def set_prim_cell_block(aseAtom, multFactor = 1, std = 'prim'):
    cell = [[multFactor]]
    
    fracCoords = aseAtom.get_scaled_positions()
    convCell = aseAtom.get_cell()
    numbers = aseAtom.get_atomic_numbers()
    
    standCell = spg.standardize_cell([convCell, fracCoords, numbers])

    primCell = spg.find_primitive(standCell)
    
    if std == 'prim':
        
        for line in primCell[0]:
            curLine = [round(a/Bohr, 10) for a in line]
            cell.append(curLine)
            
    elif std == 'crys':
        for line in standCell[0]:
            curLine = [round(a/Bohr, 10) for a in line]
            cell.append(curLine)
    
    return cell


