def path_from_seekpath(compound, numCalcPoint=250, contPath=False, numDig=6):
    pathInput = []
    
    #  create fractional coordinates from ase atoms object
    fracCoord_pc = compound.get_scaled_positions()
    # for atom in compound.positions:
    #     fracAtom = []
    #     for num, coord in enumerate(atom):
    #         fracAtom.append(round(coord/compound.cell[num][num], 6))
    #     fracCoord_pc.append(fracAtom)    
    
    #  use seekpath 
    path = seekpath.get_path((compound.cell, fracCoord_pc, compound.numbers))
    point_coords = path.get('point_coords') #  type: dict class
    k_path = path.get('path') #  type: simple List object
    
    #  rearange the k-ponits from the special points List for KPMODE = 1 inputs    
    kpointList = []

    
    for key in point_coords:
        curPoint = []
        coords = point_coords.get(key)
        for coord in coords:
            curPoint.append(round(coord, numDig))
        curPoint.append('# ' + str(key))
        kpointList.append(curPoint)

        
    #  create the path as a List already formatted for alamode
    for pos, point in enumerate(k_path):
        line = []
        if pos < len(k_path)-1:  #  To add a path between two path fragments in case the plot should look nicer/there are problems with non-continuous paths
            if point[1] != k_path[pos+1][0] and contPath == True:
                k_path.insert(pos+1, (point[1], k_path[pos+1][0]))
            
        startPoint = point[0]
        endPoint = point[1]
        for key in point_coords:
            if key == startPoint:
                line.append(str(key))
                coords = point_coords.get(key)
                for coord in coords:
                    line.append(round(coord, numDig))
                continue
            
        for key in point_coords:
            if key == endPoint:
                line.append(str(key))
                coords = point_coords.get(key)
                for coord in coords:
                    line.append(round(coord, numDig))
                    
        line.append(numCalcPoint)            
        pathInput.append(line)

    return pathInput, kpointList


#  function to set get input for the &kpoint block
#  compound: ASE atoms object of the analyzed compound
#  kpointSource: source of the method to obtain the k-points (up to this point ase inbuild methods and seeKpath are supported); "ase" set as default since seeKpath might not be installed
#  KPMODE: ALAMODE attribute of the &kpoint field, will generate appropriate input list for each case 0, 1, 2
#  numCalcPoint: relevant for KPMODE == 1; will set the number of points to be along a path between two k-points; default of 250 points
#  contPath: relevant for KPMODE == 1; boolean; set True if the k-path should be continous e.g. Γ—X—M—Γ—R—X|R—M is set to Γ—X—M—Γ—R—X-R—M
#  DOS_kgrid: relevant for KPMODE == 2; sets the k-grid for DOS calculations; default is 20 (not sure if that value is any good though)

def set_kpoint_block(compound, kpointSource='ase', KPMODE=1, numCalcPoint=250, contPath=False, DOS_kgrid=20):
    
    kpointBlock = []
    
    #  get the k-point coordinates and the path from selected source (ase is default, since seekpath might not be installed by default)
    if kpointSource == 'ase':
        pathInput, kpointList = path_from_ase_atom(compound, numCalcPoint=numCalcPoint, contPath=contPath)
    elif kpointSource == 'seekpath':
        pathInput, kpointList = path_from_seekpath(compound, numCalcPoint=numCalcPoint, contPath=contPath)
    else:
        print('Invalid k-point source selected, please select "ase" or "seekpath"!')
        pathInput = []
        kpointList= []
    
    
    
    if KPMODE == 0:  #  Calculate phonon frequencies at given k-points
        kpointBlock.append([0])
        
        for line in kpointList:
            kpointBlock.append(line)
        
    elif KPMODE == 1:  #  Band dispersion calculation
        kpointBlock.append([1])
        
        for line in pathInput:
            kpointBlock.append(line)
        
    elif KPMODE == 2:  #  Uniform k grid for phonon DOS and thermal conductivity
        kpointBlock.append([2])
        
        kpointBlock.append([DOS_kgrid, DOS_kgrid, DOS_kgrid])
    
    
    return kpointBlock


  #  this functions writes an ANPHON input based on one ASE atoms object
  #  by default it adds the &cell and &kpoint based on the passed attributes and object

def write_ANPHON_input(aseAtom, generalInput=None, scphInput=None, qhaInput=None, relaxInput=None, strainInput=None, displaceInput=None, DISPMODE=None, analysisInput=None, multFactor=1, fileName='', source='ase', KPMODE=1, numCalcPoint=250, contPath=False, DOS_kgrid=20, stdIn = 'prim', **kwargs):
    
    #  function that writes the ANPHON input based on one ASE atoms object and instances of the general and interaction class, that hold the corresponding keywords for the calculation
    #  optional possibility to set a filename
    

    
    if fileName != '' and fileName.endswith('.in'):
        ANPHONinput = fileName
    elif fileName != '' and fileName.endswith('.in') == False:
        ANPHONinput = fileName + '.in'
    else:
        ANPHONinput = 'ANPHONinput.in'
        
    with open(ANPHONinput, 'w') as file:
        
        if generalInput != None:
            file.write('&general\n')
            
            #  get all overview of all attributes of the general object
            generalCom = generalInput.get_all_att()
    
            #  iterate over all attributes of the general object, only consider those that were set (thus are not NONE), get their value and print it
            for com in generalCom:
                if generalCom.get(com) != None:
                    file.write(' ' + com + ' = ')
                    
                    if type(generalCom.get(com)) == list:
                        for val in generalCom.get(com):
                            file.write(str(val) + ' ')
                    else:
                        file.write(str(generalCom.get(com)))
                    file.write('\n')
                    
            file.write('/\n\n\n')
        
        
        if scphInput != None:
            file.write('&scph\n')
            
            scphCom = scphInput.get_all_att()
            
            for com in scphCom:
                if scphCom.get(com) != None:
                    file.write(' ' + com + ' = ')
                    
                    if type(scphCom.get(com)) == list:
                        for val in scphCom.get(com):
                            file.write(str(val) + ' ')
