#  function to get the band path with the build-in functions of ase
#  "contPath" is a boolean that automatically converts dividers ',' in the standard path to a continous path between adjacent, normally broken off, points if TRUE, otherwise path is read in as it is
#  "numCalcPoint" is an int to set how many points should be calculated between two k-points

def path_from_ase_atom(compound, numCalcPoint=250, contPath=False):
    #  get the bravais lattice from primitive cell
    lattice = compound.cell.get_bravais_lattice()
    
    #  get the special points from bravais lattice; dict
    special_points = lattice.get_special_points()
    
    #  get the band path
    ase_path = lattice.bandpath().path    
        
    #  rearange the k-ponits from the special points List for KPMODE = 1 inputs    
    kpointList = []

    
    for key in special_points:
        curPoint = []
        coords = special_points.get(key)
        for coord in coords:
            curPoint.append(coord)
        curPoint.append('# ' + str(key))
        kpointList.append(curPoint)

    k_path = []
    
    for pos, letter in enumerate(ase_path):
        if letter.isalpha() == False:
            if letter.isdigit() == True:
                k_path[-1] += letter 
    
            elif letter == ',':
                k_path.append(letter)
        else:
            k_path.append(letter)



    #  create a list that stores the information in ALAMODE format for the band path that gets returned
    pathInput = []
    
    for pos, point in enumerate(k_path[:-1]):
        line = []
        
        if point != ',' and k_path[pos+1] != ',':
            
            startPoint = special_points.get(point)
            endPoint = special_points.get(k_path[pos+1])
            line.append(point)
            for coord in startPoint:
                line.append(coord)
            line.append(k_path[pos+1])
            for coord in endPoint:
                line.append(coord)
            line.append(numCalcPoint)
            
        elif point == ',' and contPath == True:
            startPoint = special_points.get(k_path[pos-1])
            endPoint = special_points.get(k_path[pos+1])
            line.append(k_path[pos-1])
            for coord in startPoint:
                line.append(coord)
            line.append(k_path[pos+1])
            for coord in endPoint:
                line.append(coord)
            line.append(numCalcPoint)
            
        else:
            continue
        
        pathInput.append(line)

    return pathInput, kpointList


#  function to get band path with seekpath package
#  "contPath" is a boolean that automatically converts jumps in the standard path to a path between adjacent points if TRUE, otherwise path is read in as it is
#  "numCalcPoint" is an int to set how many points should be calculated between two k-points

